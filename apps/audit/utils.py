def _client_ip(request):
    xff = request.META.get("HTTP_X_FORWARDED_FOR", "")
    if xff:
        return xff.split(",")[0].strip()
    return request.META.get("REMOTE_ADDR")


def _format_action_notification(action, module, record, old, new, user):
    """Format human-readable title and message for admin popup alerts."""
    actor_name = user.username if user and getattr(user, "is_authenticated", False) else "System"

    # 1. Attendance actions
    if action == "attendance.bulk_mark":
        count = new.get("count") if isinstance(new, dict) else None
        count_str = f" for {count} athletes" if count else ""
        return (
            "Attendance Marked",
            f"Attendance was recorded{count_str} in {record} by {actor_name}."
        )
    elif action == "attendance.photo_analyze":
        present = new.get("present_count") if isinstance(new, dict) else None
        p_str = f" ({present} verified present)" if present is not None else ""
        return (
            "AI Photo Attendance Processed",
            f"AI facial attendance analyzed for {record}{p_str}."
        )
    elif action == "attendance.correct":
        new_status = new.get("status") if isinstance(new, dict) else "corrected"
        return (
            "Attendance Corrected",
            f"Attendance record ({record}) updated to '{new_status}' by {actor_name}."
        )

    # 2. Trainer salary / fee actions
    elif action == "trainerfee.pay":
        amt = new.get("amount") if isinstance(new, dict) else ""
        amt_str = f"₹{amt} " if amt else ""
        return (
            "Trainer Salary / Payout Credited",
            f"{amt_str}salary payout was credited ({record}) by {actor_name}."
        )
    elif action == "trainerfee.generate":
        return (
            "Trainer Salaries Generated",
            f"Monthly trainer fee payables were calculated and generated by {actor_name}."
        )
    elif action == "trainerfee.verify":
        return (
            "Trainer Salary Verified",
            f"Trainer payable ({record}) was verified for payout by {actor_name}."
        )

    # 3. Student fee actions
    elif action == "fee.offline_payment":
        amt = new.get("amount") if isinstance(new, dict) else ""
        amt_str = f"₹{amt} " if amt else ""
        return (
            "Student Fee Payment Received",
            f"Fee payment {amt_str}received for {record} by {actor_name}."
        )
    elif action == "fee.allocate":
        return (
            "Fee Structure Allocated",
            f"Student fee allocated for {record} by {actor_name}."
        )
    elif action == "payment.verify":
        return (
            "Online Payment Verified",
            f"Payment verified for {record}."
        )

    # 4. Student enrollment actions
    elif action == "student.create":
        sid = new.get("student_id") if isinstance(new, dict) else record
        return (
            "New Student Enrolled",
            f"Athlete {sid} was registered by {actor_name}."
        )
    elif action == "student.update":
        return (
            "Student Details Updated",
            f"Student details ({record}) were modified by {actor_name}."
        )

    # 5. Session actions
    elif action == "session.create":
        return (
            "Session Scheduled",
            f"New training session scheduled ({record}) by {actor_name}."
        )
    elif action == "session.status":
        st = new.get("status") if isinstance(new, dict) else "updated"
        return (
            "Session Status Changed",
            f"Session {record} status changed to '{st}' by {actor_name}."
        )

    # 6. Batch actions
    elif action == "batch.create":
        nm = new.get("name") if isinstance(new, dict) else record
        return (
            "New Batch Created",
            f"Training batch '{nm}' created by {actor_name}."
        )
    elif action == "batch.update":
        return (
            "Batch Updated",
            f"Batch {record} was updated by {actor_name}."
        )

    # 7. Trainer coach actions
    elif action == "trainer.checkin":
        return (
            "Trainer Checked In",
            f"Coach arrival/check-in logged for {record}."
        )
    elif action == "trainer.leave_request":
        return (
            "Trainer Leave Request",
            f"Coach submitted a leave request ({record})."
        )
    elif action == "trainer.leave_decide":
        return (
            "Trainer Leave Decided",
            f"Leave request ({record}) was decided by {actor_name}."
        )

    # 8. User / security actions
    elif action == "user.password_reset":
        return (
            "User Password Reset",
            f"Password reset issued for {record} by {actor_name}."
        )

    # 9. Generic notable actions
    elif module in ("attendance", "fees", "trainer_fees", "sessions", "students", "batches", "payments", "coaches"):
        title = action.replace(".", " ").replace("_", " ").title()
        return (
            title,
            f"{title} action completed ({record}) by {actor_name}."
        )

    return None


def log_audit(request, action, module, record="", old=None, new=None):
    from .models import AuditLog
    user = getattr(request, "user", None)
    try:
        AuditLog.objects.create(
            user=user if user and user.is_authenticated else None,
            action=action, module=module, record=record or "",
            old_value=old or {}, new_value=new or {},
            ip_address=_client_ip(request) if request else None,
        )
    except Exception:
        pass  # audit must never break the request

    # Dispatch in-app popup notification to Admins & Super Admins
    try:
        formatted = _format_action_notification(action, module, record, old, new, user)
        if formatted:
            title, message = formatted
            from apps.notifications.utils import notify_admins
            school_id = getattr(user, "school_id", None) if user and getattr(user, "is_authenticated", False) else None
            notify_admins(title, message, school_id=school_id)
    except Exception:
        pass
